local AT400 = { window = { point = "BOTTOMLEFT", x = 400, y = 300, w = 410, h = 306 } }

local function corner(f)
    local p, rel, rp, x, y = f:GetPoint(1)
    assert(p == "BOTTOMLEFT" and rp == "BOTTOMLEFT", "anchored by its bottom-left corner")
    return x, y, rel
end

T.it("the first window opens where the window's chat column would be, at its size", function()
    local G, W, ns, UI = separate({ db = AT400 })
    whisper(W, "hey", "Aaa")
    local f = winOf(ns, "aaa").frame
    local x, y, rel = corner(f)
    T.eq(rel, G.UIParent)
    T.eq(x, 446, "right of where the rail would be")
    T.eq(y, 300)
    T.eq(f:GetWidth(), 364, "the chat column's size")
    T.eq(f:GetHeight(), 306)
end)

T.it("the next windows step down and right; a minimised window's step is free again", function()
    local G, W, ns, UI = separate({ db = AT400 })
    whisper(W, "a", "Aaa")
    whisper(W, "b", "Bbb")
    whisper(W, "c", "Ccc")
    local bx, by = corner(winOf(ns, "bbb").frame)
    T.eq(bx, 472); T.eq(by, 274)
    local cx, cy = corner(winOf(ns, "ccc").frame)
    T.eq(cx, 498); T.eq(cy, 248)
    winOf(ns, "bbb").pane.head.close:Click()
    whisper(W, "d", "Ddd")
    local dx, dy = corner(winOf(ns, "ddd").frame)
    T.eq(dx, 472, "takes Bbb's free step")
    T.eq(dy, 274)
end)

T.it("a moved window keeps its place for its conversation, also after a reload", function()
