local T = T

-- Separate windows (Settings, Look): every conversation in its own window, as in WIM.

local function load(opts)
    local G, W, ns = T.load(opts)
    return G, W, ns, ns.UI
end

T.it("Separate windows is off by default and is the first row under Look", function()
    local G, W, ns, UI = load()
    T.eq(ns.Get("separate"), false, "off by default")
    UI.ShowSettings()
    local C = ns.Settings.controls
    local switch = C.separate
    T.ok(switch, "a Separate windows control")
    local row = switch:GetParent()
    T.eq(row.label:GetText(), "Separate windows")
    T.eq(row.desc:GetText(), "Each conversation in its own window, as in WIM")
    T.ok(C.intercept:GetParent():GetTop() > row:GetTop() and row:GetTop() > C.accent:GetParent():GetTop(),
        "between When you whisper and Accent")
    switch:Click()
    T.eq(ns.Get("separate"), true, "the switch turns it on")
end)

local function whisper(W, text, sender, o)
    W.chat("CHAT_MSG_WHISPER", W.whisperArgs(text, sender, o))
end

-- Sotto with Separate windows on.
local function separate(opts)
    local G, W, ns, UI = load(opts)
    ns.Set("separate", true)
    return G, W, ns, UI
end

local function winOf(ns, key) return ns.Windows.For(ns.Store.Get(key)) end

local function lines(w)
    local out = {}
    for _, it in ipairs(w.pane.log.items) do if it.kind == "line" then out[#out + 1] = it.msg.m end end
    return out
end

