local function box(f) return f:GetLeft(), f:GetBottom(), f:GetRight(), f:GetTop() end

local function overlaps(a, b)
    local al, ab, ar, at = box(a)
    local bl, bb, br, bt = box(b)
    return al < br and bl < ar and ab < bt and bb < at
end

-- What Esc does: Blizzard hides every shown frame named in UISpecialFrames.
local function esc(G)
    for _, name in ipairs(G.UISpecialFrames) do
        local f = G[name]
        if f and f:IsShown() then f:Hide() end
    end
end

