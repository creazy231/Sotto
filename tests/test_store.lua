local T = T
local CHAR = "Player-1-00000001"

local function load(opts)
    local G, W, ns = T.load(opts)
    return G, W, ns, ns.Store
end

T.it("character conversations live under the character", function()
    local G, W, ns, S = load()
    local c, isNew = S.Ensure("w", "Tarin Ashgrove")
    T.ok(isNew, "new")
    T.eq(G.SottoDB.chars[CHAR].convs["tarin ashgrove"], c)
    T.eq(c.kind, "w")
    T.eq(c.name, "Tarin Ashgrove")
    T.eq(c.unread, 0)
    T.eq(#c.msgs, 0)
end)

T.it("Battle.net conversations are shared and keyed by BattleTag", function()
    local G, W, ns, S = load()
    local c = S.Ensure("bn", "Alex", { tag = "Alex#1234", bnID = 5 })
    T.eq(G.SottoDB.bn["bn:alex#1234"], c)
    T.eq(c.bnID, 5)
    T.eq(c.tag, "Alex#1234")
end)

T.it("Battle.net conversations without a readable BattleTag use the session id", function()
    local G, W, ns, S = load()
    local c = S.Ensure("bn", "|Kq5|k", { bnID = 5 })
    T.eq(c.key, "bn:id:5")
end)

T.it("Ensure returns the same conversation for name variants", function()
    local G, W, ns, S = load()
    local a = S.Ensure("w", "Tarin Ashgrove")
    local b, isNew = S.Ensure("w", "tarin ashgrove")
    T.eq(a, b)
    T.no(isNew)
end)

T.it("Ensure refuses bad names", function()
    local G, W, ns, S = load()
    T.eq(S.Ensure("w", nil), nil)
    T.eq(S.Ensure("w", T.secret("x")), nil)
end)

T.it("Add keeps at most 400 messages and updates last", function()
    local G, W, ns, S = load()
    local c = S.Ensure("w", "Tarin Ashgrove")
    local now = G.time()
    for i = 1, 405 do S.Add(c, "i", "m" .. i, now + i) end
    T.eq(#c.msgs, 400)
    T.eq(c.msgs[1].m, "m6")
    T.eq(c.last, now + 405)
end)

T.it("Add fires MESSAGE_ADDED", function()
    local G, W, ns, S = load()
    local seen
    ns.Listen("MESSAGE_ADDED", function(conv, msg) seen = msg.m end)
    S.Add(S.Ensure("w", "Tarin Ashgrove"), "o", "hi")
    T.eq(seen, "hi")
end)

T.it("List shows open conversations newest first", function()
    local G, W, ns, S = load()
    local a = S.Ensure("w", "Aaa")
    local b = S.Ensure("w", "Bbb")
    local c = S.Ensure("bn", "Alex", { tag = "Alex#1", bnID = 1 })
    local now = G.time()
    S.Add(a, "i", "x", now + 100)
    S.Add(b, "i", "x", now + 300)
    S.Add(c, "i", "x", now + 200)
    local l = S.List()
    T.eq(#l, 3)
    T.eq(l[1], b)
    T.eq(l[2], c)
    T.eq(l[3], a)
end)

T.it("a conversation's first message sets its recency, even an older one", function()
    local G, W, ns, S = load()
    local now = G.time()
    local old = S.Ensure("w", "Old")
    S.Add(old, "i", "from the history", now - 2 * 86400)
    local fresh = S.Ensure("w", "Fresh")
    S.Add(fresh, "i", "just now", now - 60)
    T.eq(old.last, now - 2 * 86400)
    local l = S.List()
    T.eq(l[1], fresh, "the conversation with the newest message first")
    T.eq(l[2], old)
end)

T.it("Close hides a conversation until a new message arrives", function()
    local G, W, ns, S = load()
    local a = S.Ensure("w", "Aaa")
    S.Add(a, "i", "x")
    S.Close(a)
    T.eq(#S.List(), 0)
    S.Add(a, "i", "again")
    T.eq(#S.List(), 1)
end)

T.it("unread totals count open conversations only", function()
    local G, W, ns, S = load()
    local a = S.Ensure("w", "Aaa")
    local b = S.Ensure("w", "Bbb")
    S.MarkUnread(a)
    S.MarkUnread(a)
    S.MarkUnread(b)
    T.eq(S.UnreadTotal(), 3)
    S.MarkRead(a)
    T.eq(S.UnreadTotal(), 1)
    S.Close(b)
    T.eq(S.UnreadTotal(), 0)
end)

T.it("Prune drops old messages and empty closed conversations", function()
    local G, W, ns, S = load()
    local now = G.time()
    local a = S.Ensure("w", "Aaa")
    S.Add(a, "i", "old", now - 40 * 86400)
    S.Add(a, "i", "new", now - 3600)
    local b = S.Ensure("w", "Bbb")
    S.Add(b, "i", "old", now - 40 * 86400)
    S.Close(b)
    S.Prune(30)
    T.eq(#a.msgs, 1)
    T.eq(a.msgs[1].m, "new")
    T.eq(S.Get("bbb"), nil, "empty closed conversation removed")
end)

T.it("history kept until logout is cleared at the next login, not by a reload", function()
    local G, W, ns, S = load()
    ns.Set("keepDays", 0)
    local a = S.Ensure("w", "Aaa")
    S.Add(a, "i", "x")
    W.fire("PLAYER_LOGOUT")
    T.eq(#a.msgs, 1, "logout itself keeps it (a reload logs out too)")
    W.fire("PLAYER_ENTERING_WORLD", false, true)
    T.eq(#a.msgs, 1, "a reload keeps it")
    W.fire("PLAYER_ENTERING_WORLD", true, false)
    T.eq(#a.msgs, 0, "the next real login clears it")
end)

T.it("retention changes apply at the next login, not at once", function()
    local G, W, ns, S = load()
    local a = S.Ensure("w", "Aaa")
    S.Add(a, "i", "old", G.time() - 20 * 86400)
    S.Add(a, "i", "new", G.time() - 60)
    ns.Set("keepDays", 7)
    T.eq(#a.msgs, 2, "nothing deleted by the click")
    W.fire("PLAYER_ENTERING_WORLD", true, false)
    T.eq(#a.msgs, 1, "pruned at login")
end)

T.it("old history is pruned at login", function()
    local now = 1794499200
    local db = { chars = { [CHAR] = { convs = { aaa = { key = "aaa", kind = "w", name = "Aaa", unread = 0, open = true,
        last = now - 50 * 86400, msgs = { { t = now - 50 * 86400, d = "i", m = "old" } } } } } } }
    local G, W, ns, S = load({ db = db })
    T.eq(S.Get("aaa"), nil)
end)
